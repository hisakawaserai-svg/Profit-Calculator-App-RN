// 「過去の記録から複製」（新規作成の初期値を、既存の記録から作る）。
//
// ## 何をする機能か
//
// **フォームの初期値が変わるだけ。** 複製を選んでも DB には何も書かない ──
// 開くのは新規作成と同じ `RecordFormSheet` で、保存を押すまでレコードは作られない
// （決定 §7-7）。「複製」という別の保存経路は作らない。
//
// ## 何を写して、何を写さないか
//
// | 写す | 写さない（空で始める） |
// |---|---|
// | 商品名 | 出品日・販売日（＝今日から） |
// | 種別・仕入価格 | 売却状態（常に出品中から） |
// | 販売価格 | |
// | 送料（＋専用資材費の控え） | |
// | 手数料率・販売サイト名 | |
// | 梱包材・その他 | |
// | メモ | |
// | 写真 | |
// | タグ | |
// | 目標利益 | |
//
// **写さないのは「複製という操作そのものに由来する欄」だけ**（決定 §7-12）。同じ商品を
// 2 つ仕入れて両方を記録するとき、送料や手数料はもちろん、販売価格も写真もメモも
// たいてい同じになる ── 空にして毎回打ち直させると、複製の値打ちがその分減る。
// 商品名を写すのは、書き換える前提でも**打ち直しよりは直すほうが速い**ため
// （「〇〇 Lサイズ」→「〇〇 Mサイズ」のような使い方）。
//
// ### 一覧に無いが写している 2 つ
//
// - **その他（othersCost）** … 送料・梱包材と同じ「前回いくらかかったか」の欄なので、
//   経費の中でこれだけ落とすと、複製したのに 1 行だけ空く
// - **販売サイト名（siteName）** … 手数料率と**同時にしか入らない**値（SPEC-V3 §4.3）。
//   率だけ写して名前を落とすと、率は 10% なのに札が消えた記録ができる
//
// ### 写真は「同じ 1 枚」ではなく複製する（media/photoFiles.ts の PhotoStore.duplicate）
//
// この関数自体はファイル名をそのまま返さない（下の photoFileName: null）。2 つの記録が
// 同じファイル名を指すと、片方を削除したときにもう片方の写真も一緒に消えてしまうため
// （db/repository.ts が削除のたびに実ファイルを直接消す作り）。実際にファイルを複製して
// 別名を割り当てる処理は、写真の後片付け（開いている間に作ったファイルの掃除）と同じ
// 場所で行う必要があるため、フォーム側（screens/RecordFormSheet.tsx の
// duplicateSourcePhotoFileName）が担う。ここでは「複製元に写真があったかどうか」しか
// 分からないので、その先の実ファイル操作はしない。
//
// ### 出品日を写さない理由
//
// 出品日は「いつ出したか」であって商品の性質ではない。写すと、今日出す物に
// 半年前の日付が入った記録ができる ── しかも販売日は出品日より前にできない（§日付のきまり）ので、
// 気付かないまま売れた日を入れられなくなる。新規作成と同じく**今日**から始める。
//
// ### 売却状態を写さない理由
//
// 「日付ではない」が、写すと**日付が壊れる**。売却状態を写して販売日を写さなければ
// 「売却済みなのに販売日が無い」という記録ができ、販売日も写せば「今日出す物が今日
// 売れたことになっている」という記録ができる。複製元が売却済みでも、作られるのは
// **これから出す記録**（決定 §7-8）── 常に出品中から始める。
//
// ## 複製元は売却済み・出品中のどちらでもよい
//
// 写すのは経費とタグと目標で、どれも**売れたかどうかと無関係**。
// 「前に売れた物の同型をまた出す」も「出品中の物をもう 1 つ出す」も同じ操作になる。

import type { SaleRecord } from '@/db/schema';

import { recordToFormValues, type RecordFormValues } from './recordForm';

/**
 * 複製元の記録から、新規フォームの初期値を作る。
 *
 * **`recordToFormValues`（編集用の展開）を土台にする。** DB の列 → フォームの文字列という
 * 変換規則（金額の 0 は空欄・目標の null と 0 の区別・資材費の控えなど）はあちらが持っており、
 * ここで書き直すと片方だけ直る事故が起きる。この関数がするのは**写さない欄を空に戻すこと**だけ。
 *
 * @param record 複製元。売却済み・出品中どちらでもよい
 * @param tagIds 複製元に付いているタグ（呼び出し側が引く。sortOrder 昇順）
 * @param now    「今日」。出品日・販売日の初期値になる（テストから固定できるように引数）
 */
export function duplicateFormValues(
  record: SaleRecord,
  tagIds: readonly string[] = [],
  now: Date = new Date(),
): RecordFormValues {
  return {
    ...recordToFormValues(record, now, tagIds),
    // ここから下が「写さない」欄。複製元が何であっても新規作成と同じ状態にする。
    // 写真は写さないのではなく「ここでは複製しない」── 実ファイルの複製は
    // screens/RecordFormSheet.tsx 側の責務（上のコメント）
    photoFileName: null,
    saleStartDate: now,
    saleDate: now,
    // 複製元が売却済みでも、作られるのは**これから出す記録**（決定 §7-8 の新規と同じ）
    isSold: false,
  };
}
