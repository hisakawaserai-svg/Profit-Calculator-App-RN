// 使いかたの本文（UI-SPEC §3.2 / 採用案 `19c` `20b` `20c`）。**文言と並びだけを持つ純粋なデータ。**
//
// `labels.ts` と分けたのは長さのため ── こちらは 1 項目が数行の地の文で、
// 画面の表示語（ボタン名・列名）を引く場所と混ぜると `labels.ts` が読めなくなる。
// 分けても原則は同じで、**画面側で文字列を組み立てない**（SPEC-V2 §5.3）。
// 図の中の語と数字だけは `HelpDiagram.tsx` が持つ（理由は同ファイルの冒頭）。
//
// ## ページは 4 枚（案 `20b`）
//
// 上部のチップで**計算 / 記録 / データ / ことば**を切り替える。
//
// **「ことば」が独立しているのが要点。** 純利益・利益・収支の使い分けや、不用品と仕入品の
// ちがいは**どの画面にも属さない** ── 画面ごとの節に押し込むと、計算にも記録にも
// データにも同じ説明を書くことになり、直すときに 3 か所が食い違う。
//
// ## CSV・タグ・写真をどこに入れたか
//
// | 内容 | ページ | 理由 |
// |---|---|---|
// | 写真 | 記録 | 付ける・外すのは記録の画面だけ。見るのは一覧と詳細で、記録の一生の中で閉じる |
// | タグ | 記録（絞り込みも含めて全部） | 「付ける」と「絞る」を別ページにすると往復させる。データ側には「同じ絞り込みがここでも効く」の 1 項目だけ置く |
// | 書き出し（CSV）＋ データの保存 | データ | 入口は設定タブだが、話は「自分のデータをまとめて取り出す・残す」こと。チップは画面名ではなく話の単位なので、ここに収まる。バックアップの注意も同じページに続けたい |
// | よく使う値（プリセット）・既定の種別 | 記録 | 目的が「記録を作るときの入力を減らす」ことなので。計算タブからも同じ印で選べることは計算ページ側から参照する |
//
// 設定タブのチップを立てないのは、設定は**入口であって話題ではない**ため。
// 「設定」を探しに来る人は既に設定タブを開いている。

