-- 手で書いたマイグレーション（drizzle-kit の生成物ではない。0007〜0012 と同じ扱い）。
-- 出品滞留アラート（お知らせ機能）の基準を「出品日からの経過日数」ではなく
-- 「値下げ（販売価格の変更）してからの経過日数」に変えるための列。
--
-- **photo_file_name（0005）と同じ形**（NULL 許容、DEFAULT なし）。
-- NULL = まだ一度も値下げしていない（＝出品時のまま）。読み取り側
-- （logic/notifications.ts の listingAlertItems）は `priceChangedAt ?? saleStartDate` で
-- フォールバックするので、この列を追加しただけでは既存レコードの見え方は変わらない
-- （既存レコードは全部 NULL のまま = 今まで通り出品日基準）。
--
-- **バックフィルはしない。** 「いつ値下げしたか」は既存データからは分からない情報で、
-- 出品日を代わりに入れてしまうと「値下げした」と偽ることになる。NULL のまま
-- フォールバックに任せるほうが正直。
ALTER TABLE `sale_records` ADD `price_changed_at` text;
