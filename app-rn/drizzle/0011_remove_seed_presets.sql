-- 手で書いたマイグレーション（drizzle-kit の生成物ではない。0007〜0010 と同じ扱い）。
-- 0002 が入れた初期プリセット 17 件（SPEC-V3 §2）を消し、**プリセットは空から始める**形にする。
--
-- 理由は多言語化（日英）。初期値は `手数料 10%` や `A4・厚さ3cm以内` のように
-- **DB の行として日本語が焼き付いている**ので、辞書（src/i18n/）では訳せない ──
-- 英語表示にしても、この 17 件だけが日本語のまま残ってしまう。
-- 訳した 17 件を言語ごとに入れ分ける手もあるが、それだと
-- 「あとから言語を変えたら、登録済みのプリセットはどうなるのか」に答えがない。
-- プリセットは元々ユーザーが自分の言葉で作るものなので、空から始めるのが筋が通る。
--
-- **0002 の INSERT は消さない**（マイグレーションは追記だけで進める）。
-- 新規インストールは 0002 で入れて 0011 で消すので、既存の端末と同じ状態に着地する。
-- 履歴を書き換えないので、既に 0002 を適用済みの端末との食い違いも起きない。
--
-- **`seed-` で始まる id だけを消す。** 利用者が自分で作ったプリセットは
-- ランダムな UUID なので巻き込まない（dev 用の投入データは `devseed-` で始まるが、
-- こちらは production のバンドルに含まれないので考えなくてよい）。
--
-- なお、利用者が初期値の名前や金額を**書き換えていた場合もこの行ごと消える** ──
-- 編集されたかどうかを見分ける列を持っていないため。記録は presets を id で参照しておらず
-- （金額を写して保存する形）、保存済みの記録は 1 件も壊れない。
DELETE FROM `presets` WHERE `id` LIKE 'seed-%';
