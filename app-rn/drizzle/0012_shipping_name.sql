-- 手で書いたマイグレーション（drizzle-kit の生成物ではない。0007〜0011 と同じ扱い）。
-- 送料プリセットの**名前の写し**を足す（SPEC-V3 §1.5.1 の扱いを送料へ広げる）。
--
-- **`site_name` と同じ形**（text NOT NULL DEFAULT ''、空文字 = 未設定）にしてある ──
-- 「そのとき何と書いてあったか」を持つ列で、プリセットの id は参照しない。
-- プリセットを直しても消しても、過去の記録に残る名前は動かない。
--
-- ## なぜ足すのか（絞り込みのためではない）
--
-- これまで送料のバッジは **postage（金額）からプリセットを逆引き**して描いていた
-- （logic/preset.ts の findPresetByValue）。記録の側に選んだ証拠が無いためで、その結果:
--
--   - プリセットを選ばず手で打っても、額が一致するプリセットのバッジが出る
--   - 設定で金額を直すと、**過去の記録のバッジが消える**（記録は何も変わっていないのに）
--   - 同じ額のプリセットが 2 件あると、並び順で先の 1 件が勝つ
--     （＝ 選んだものと違うプリセットのバッジが出る）
--
-- 名前を記録の側に持てば、どれも「記録に書いてある名前で引く」だけで解ける。
--
-- ## 既存の行は空文字で埋まる
--
-- DEFAULT '' を置くのは `site_name`（0004）と同じ理由で、既存行を書き換えないため。
-- **空文字の記録は従来どおり金額で逆引きする**（logic/preset.ts の resolvePresetTag）──
-- この列を足す前に保存された記録の見た目を変えないための措置で、
-- 名前が入っている記録だけが名前で引かれる。
ALTER TABLE `sale_records` ADD `shipping_name` text DEFAULT '' NOT NULL;
